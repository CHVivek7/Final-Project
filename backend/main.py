# ─────────────────────────────────────────────────────────────────────────────
# Risk classification — voting on per-endpoint learned thresholds
# ─────────────────────────────────────────────────────────────────────────────
def classify_risk_from_probs(tox_probs: dict) -> dict:
    max_prob   = max(tox_probs.values())
    top_target = max(tox_probs, key=tox_probs.get)

    if _thresholds_data is None:
        if max_prob >= 0.55:   risk = "HIGH"
        elif max_prob >= 0.30: risk = "MEDIUM"
        else:                  risk = "LOW"
        return {"risk_level": risk, "max_prob": round(max_prob, 4),
                "top_target": top_target, "high_vote_count": 0,
                "med_vote_count": 0, "high_voters": []}

    high_t           = _thresholds_data["high_thresholds"]
    med_t            = _thresholds_data["medium_thresholds"]
    useful_endpoints = _thresholds_data["useful_endpoints"]   # only signal endpoints
    min_high_votes   = _thresholds_data["min_high_votes"]     # learned optimal

    high_votes = [(t, p) for t, p in tox_probs.items()
                  if t in useful_endpoints and p >= high_t.get(t, 0.50)]
    med_votes  = [(t, p) for t, p in tox_probs.items()
                  if t in useful_endpoints and p >= med_t.get(t, 0.20)]

    if len(high_votes) >= min_high_votes:
        risk = "HIGH"
    elif len(med_votes) >= 1:
        risk = "MEDIUM"
    else:
        risk = "LOW"

    return {
        "risk_level":      risk,
        "max_prob":        round(max_prob, 4),
        "top_target":      top_target,
        "high_vote_count": len(high_votes),
        "med_vote_count":  len(med_votes),
        "high_voters":     [t for t, _ in high_votes],
    }

# ─────────────────────────────────────────────────────────────────────────────
# PubChem molecule info
# ─────────────────────────────────────────────────────────────────────────────
def fetch_molecule_info(smiles: str) -> Dict[str, str]:
    try:
        cid_res = requests.get(
            f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/smiles/{smiles}/cids/JSON",
            timeout=5,
        )
        if cid_res.status_code != 200:
            return {"common_name": "Unknown", "iupac_name": "Unknown", "formula": ""}

        cid = cid_res.json()["IdentifierList"]["CID"][0]

        prop_res = requests.get(
            f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/{cid}/property/IUPACName,MolecularFormula/JSON",
            timeout=5,
        )
        props = prop_res.json()["PropertyTable"]["Properties"][0]

        syn_res = requests.get(
            f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/{cid}/synonyms/JSON",
            timeout=5,
        )
        synonyms = syn_res.json()["InformationList"]["Information"][0].get("Synonym", [])
        common_name = next(
            (n for n in synonyms if len(n) < 30 and n.isalpha()), "Unknown"
        )
        return {
            "common_name": common_name,
            "iupac_name":  props.get("IUPACName", "Unknown"),
            "formula":     props.get("MolecularFormula", ""),
        }
    except Exception:
        return {"common_name": "Unknown", "iupac_name": "Unknown", "formula": ""}

